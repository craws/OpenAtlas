def clean_value(val: Any) -> Any:
    if pd.isna(val):
        return None
    if isinstance(val, str):
        val = val.strip()
        return val if val != '' else None
    return val


def normalize_ind_nr(ind_nr_raw: Any) -> Optional[str]:
    if pd.isna(ind_nr_raw):
        return None
    if isinstance(ind_nr_raw, (int, float)):
        return str(int(ind_nr_raw))
    s = str(ind_nr_raw).strip()
    if not s:
        return None
    try:
        f = float(s)
        if f == int(f):
            return str(int(f))
        return str(f)
    except ValueError:
        return s


def get_sort_key(ind_nr: str) -> Any:
    match = re.search(r'(\d+)', ind_nr)
    if match:
        return int(match.group(1))
    return ind_nr


def parse_anthro_data(file_path: Path) -> list[AnthroIndividual]:
    if not file_path.exists():
        raise FileNotFoundError(f"File not found: {file_path}")

    excel = pd.ExcelFile(file_path)
    sheet_names = excel.sheet_names[1:]

    individuals: dict[str, AnthroIndividual] = {}

    # Define mapping from sheet name to attribute name on AnthroIndividual
    sheet_mapping = {
        "General & Demographics": "general_demographics",
        "Sex": "sex",
        "Age": "age",
        "Height": "height",
        "Preservation": "preservation",
        "Additional Sampling": "additional_sampling",
        "Inventory Teeth": "inventory_teeth",
        "Teeth Pathologies": "teeth_pathologies",
        "Inventory Skull": "inventory_skull",
        "Skull pathologies": "skull_pathologies",
        "Inventory Postcranium": "inventory_postcranium",
        "Postcranium Pathologies": "postcranium_pathologies",
        "Joint Pathologies": "joint_pathologies",
        "Scoliosis": "scoliosis",
        "Inventory Vertebrae": "inventory_vertebrae",
        "Vertebrae Pathologies": "vertebrae_pathologies",
        "Trauma": "trauma",
        "Tumors": "tumors",
        "Rickets": "rickets",
        "Miscellaneous": "miscellaneous"}

    # Mapping from sheet name to Class
    class_mapping = {
        "General & Demographics": GeneralDemographicsData,
        "Sex": SexData,
        "Age": AgeData,
        "Height": HeightData,
        "Preservation": PreservationData,
        "Additional Sampling": AdditionalSamplingData,
        "Inventory Teeth": InventoryTeethData,
        "Teeth Pathologies": TeethPathologiesData,
        "Inventory Skull": InventorySkullData,
        "Skull pathologies": SkullPathologiesData,
        "Inventory Postcranium": InventoryPostcraniumData,
        "Postcranium Pathologies": PostcraniumPathologiesData,
        "Joint Pathologies": JointPathologiesData,
        "Scoliosis": ScoliosisData,
        "Inventory Vertebrae": InventoryVertebraeData,
        "Vertebrae Pathologies": VertebraePathologiesData,
        "Trauma": TraumaData,
        "Tumors": TumorsData,
        "Rickets": RicketsData,
        "Miscellaneous": MiscellaneousData}

    # 1. Read 'General & Demographics' first
    main_sheet = 'General & Demographics'
    if main_sheet in sheet_names:
        df_gen = pd.read_excel(excel, sheet_name=main_sheet)
        if isinstance(df_gen, pd.DataFrame):
            for _, row in df_gen.iterrows():
                ind_nr = normalize_ind_nr(row.get('Ind. Nr.'))
                if not ind_nr:
                    continue

                obj = class_mapping[main_sheet](sheet_name=main_sheet)
                for col in df_gen.columns:
                    if col == 'Ind. Nr.':
                        continue
                    val = clean_value(row[col])
                    if val is not None:
                        attr = to_attribute_name(col)
                        if hasattr(obj, attr):
                            setattr(obj, attr, val)
                        else:
                            obj.data[col] = val

                individuals[ind_nr] = AnthroIndividual(ind_nr=ind_nr)
                setattr(individuals[ind_nr], sheet_mapping[main_sheet], obj)

    # 2. Process all other sheets
    for sheet in sheet_names:
        if sheet == main_sheet:
            continue

        df = pd.read_excel(excel, sheet_name=sheet)
        if not isinstance(df, pd.DataFrame):
            continue

        for _, row in df.iterrows():
            ind_nr = normalize_ind_nr(row.get('Ind. Nr.'))
            if not ind_nr or ind_nr not in individuals:
                continue

            obj = class_mapping[sheet](sheet_name=sheet)
            for col in df.columns:
                if col == 'Ind. Nr.':
                    continue
                val = clean_value(row[col])
                if val is not None:
                    attr = to_attribute_name(col)
                    if hasattr(obj, attr):
                        setattr(obj, attr, val)
                    else:
                        obj.data[col] = val

            setattr(individuals[ind_nr], sheet_mapping[sheet], obj)

    sorted_list = sorted(
        individuals.values(), key=lambda x: get_sort_key(x.ind_nr))
    return sorted_list


