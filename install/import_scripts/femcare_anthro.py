def to_attribute_name(name: str) -> str:
    if not name:
        return 'unknown'
    s = name.strip().lower()
    s = re.sub(r'[^a-z0-9_]', '_', s)
    s = re.sub(r'_+', '_', s)
    s = s.strip('_')
    if not s:
        return 'unknown'
    if s[0].isdigit():
        s = 'f_' + s
    return s


@dataclass
class AnthroSheet:
    sheet_name: str
    data: dict[str, Any] = field(default_factory=dict)

    def get_all_data(self) -> dict[str, Any]:
        res = self.data.copy()
        for k, v in self.__dict__.items():
            if k not in ('sheet_name', 'data') and v is not None:
                res[k] = v
        return dict(sorted(res.items()))


