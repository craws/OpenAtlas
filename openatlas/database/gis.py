import ast
from collections import defaultdict
from typing import Any

from flask import g
from shapely import GeometryCollection, from_wkt


def get_by_id(id_: int) -> list[dict[str, Any]]:
    g.cursor.execute(
        """
        SELECT
            g.id,
            g.name,
            g.description,
            g.type,
            public.ST_AsGeoJSON(geom_point) AS point,
            public.ST_AsGeoJSON(geom_linestring) AS linestring,
            public.ST_AsGeoJSON(ST_ForcePolygonCCW(geom_polygon)) AS polygon
        FROM model.entity place
        JOIN model.gis g ON place.id = g.entity_id
        WHERE place.id = %(id_)s;
        """,
        {'id_': id_})
    return [get_geometry_dict(row) for row in list(g.cursor)]


# Geometries of the entities themselves and of places linked to them
TARGETS = """
    WITH targets AS (
        SELECT id AS entity_id, id AS location_id
        FROM model.entity
        WHERE id IN %(ids)s
        UNION
        SELECT domain_id AS entity_id, range_id AS location_id
        FROM model.link
        WHERE property_code IN ('P74', 'OA8', 'OA9', 'P7', 'P26', 'P27')
        AND domain_id IN %(ids)s)
    """


def get_by_entity_ids(ids: list[int]) -> dict[int, list[dict[str, Any]]]:
    if not ids:
        return {}
    g.cursor.execute(
        TARGETS + """
        SELECT
            g.id,
            t.entity_id,
            t.location_id,
            g.name,
            g.description,
            g.type,
            public.ST_AsGeoJSON(geom_point) AS point,
            public.ST_AsGeoJSON(geom_linestring) AS linestring,
            public.ST_AsGeoJSON(ST_ForcePolygonCCW(geom_polygon)) AS polygon
        FROM targets t
        JOIN model.gis g ON g.entity_id = t.location_id
        WHERE geom_point IS NOT NULL
            OR geom_linestring IS NOT NULL
            OR geom_polygon IS NOT NULL
        ORDER BY t.entity_id, g.id, t.location_id;
        """,
        {'ids': tuple(ids)})
    locations = defaultdict(list)
    for row in list(g.cursor):
        locations[row['entity_id']].append(get_geometry_dict(row))
    return locations


def get_geometry_dict(row: dict[str, Any]) -> dict[str, Any]:
    if row['point']:
        geometry = ast.literal_eval(row['point'])
    elif row['linestring']:
        geometry = ast.literal_eval(row['linestring'])
    else:
        geometry = ast.literal_eval(row['polygon'])
    geometry['title'] = row['name'].replace('"', '\"') \
        if row['name'] else ''
    geometry['description'] = row['description'].replace('"', '\"') \
        if row['description'] else ''
    geometry['shapeType'] = (
        row['type'].replace('"', '\"')) if row['type'] else ''
    geometry['locationId'] = row.get('location_id')
    geometry['placeId'] = row.get('entity_id')
    return geometry


def get_centroids_by_entities(ids: list[int]) -> dict[int, list[Any]]:
    g.cursor.execute(
        TARGETS + """
        SELECT
            g.id,
            t.entity_id,
            t.location_id,
            g.name,
            g.description,
            g.type,
            CASE WHEN geom_linestring IS NULL THEN NULL ELSE
                public.ST_AsGeoJSON(public.ST_PointOnSurface(geom_linestring))
                END AS linestring_point,
            CASE WHEN geom_polygon IS NULL THEN NULL ELSE
                public.ST_AsGeoJSON(public.ST_PointOnSurface(geom_polygon))
                END AS polygon_point
        FROM targets t
        JOIN model.gis g ON g.entity_id = t.location_id
        WHERE geom_linestring IS NOT NULL OR geom_polygon IS NOT NULL
        ORDER BY t.entity_id, g.id, t.location_id;
        """,
        {'ids': tuple(ids)})
    locations = defaultdict(list)
    for row in list(g.cursor):
        locations[row['entity_id']].append(get_centroid_dict(row))
    return locations


def get_centroid_dict(row: dict[str, Any]) -> dict[str, Any]:
    if row['linestring_point']:
        geometry = ast.literal_eval(row['linestring_point'])
    elif row['polygon_point']:
        geometry = ast.literal_eval(row['polygon_point'])
    else:
        return {}  # pragma: no cover, because ignored by optimizer
    geometry['title'] = \
        (row['name'].replace('"', '\"') if row['name'] else '') \
        + '(autogenerated)'
    geometry['description'] = row['description'].replace('"', '\"') \
        if row['description'] else ''
    geometry['shapeType'] = 'centerpoint'
    geometry['locationId'] = row.get('location_id')
    geometry['placeId'] = row.get('entity_id')
    return geometry


def get_wkt_by_id(id_: int) -> str:
    g.cursor.execute(
        """
        SELECT
            g.id,
            g.name,
            g.description,
            g.type,
            public.ST_AsText(geom_point) AS point,
            public.ST_AsText(geom_linestring) AS linestring,
            public.ST_AsText(ST_ForcePolygonCCW(geom_polygon)) AS polygon
        FROM model.entity place
        JOIN model.gis g ON place.id = g.entity_id
        WHERE place.id = %(id_)s;
        """,
        {'id_': id_})
    geometries = []
    for row in g.cursor:
        if row['point']:
            geometries.append(from_wkt(row['point']))
        if row['linestring']:
            geometries.append(from_wkt(row['linestring']))
        if row['polygon']:
            geometries.append(from_wkt(row['polygon']))
    if not geometries:
        return ""
    if len(geometries) == 1:
        return geometries[0].wkt
    return GeometryCollection(geometries).wkt


def get_all(extra_ids: list[int]) -> list[dict[str, Any]]:
    g.cursor.execute(
        """
        SELECT
            g.entity_id,
            g.id,
            g.name,
            g.description,
            g.type,
            public.ST_AsGeoJSON(geom_point) AS point,
            public.ST_AsGeoJSON(geom_linestring) AS linestring,
            public.ST_AsGeoJSON(ST_ForcePolygonCCW(geom_polygon)) AS polygon,
            CASE WHEN geom_polygon IS NULL THEN NULL ELSE
                public.ST_AsGeoJSON(public.ST_PointOnSurface(geom_polygon))
                END AS polygon_point,
            e.id AS entity_id,
            e.name AS entity_name,
            e.description AS entity_description,
            string_agg(CAST(t.range_id AS text), ',') AS types
        FROM model.gis g
        JOIN model.entity e ON g.entity_id = e.id
        LEFT JOIN model.link t ON e.id = t.domain_id AND t.property_code = 'P2'
        WHERE e.openatlas_class_name = 'place' OR e.id IN %(extra_ids)s
        GROUP BY e.id, g.id;
        """,
        {'extra_ids': tuple(extra_ids)})
    return list(g.cursor)


def test_geom(geometry: str) -> bool:
    g.cursor.execute(
        """
        SELECT st_isvalid(
            public.ST_SetSRID(public.ST_GeomFromGeoJSON(%(geojson)s), 4326));
        """,
        {'geojson': geometry})
    return bool(g.cursor.fetchone()['st_isvalid'])


def insert(data: dict[str, Any], shape: str) -> None:
    g.cursor.execute(
        f"""
        INSERT INTO model.gis (
            entity_id, name, description, type, geom_{shape}
        ) VALUES (
            %(entity_id)s, %(name)s, %(description)s, %(type)s,
            public.ST_SetSRID(public.ST_GeomFromGeoJSON(%(geojson)s),4326)
        );
        """,
        data)


def delete_by_entity_id(id_: int) -> None:
    g.cursor.execute(
        'DELETE FROM model.gis WHERE entity_id = %(id)s;',
        {'id': id_})
